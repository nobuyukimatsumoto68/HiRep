static int file_exists(const char *name) {
    return access(name, F_OK) == 0;
}

/* byte copy src -> dst (PID 0 only) */
static void copy_file(const char *src, const char *dst) {
    FILE *in = fopen(src, "rb");
    error(in == NULL, 1, "copy_file", "cannot open source");
    FILE *out = fopen(dst, "wb");
    error(out == NULL, 1, "copy_file", "cannot open destination");
    static char buf[1 << 20];
    size_t nr;
    while ((nr = fread(buf, 1, sizeof(buf), in)) > 0) {
        size_t nw = fwrite(buf, 1, nr, out);
        error(nw != nr, 1, "copy_file", "short write");
    }
    error(ferror(in), 1, "copy_file", "read error");
    fclose(in);
    error(fclose(out) != 0, 1, "copy_file", "close error");
}

/* <h5> -> <h5>.bak, atomically through <h5>.bak.tmp (PID 0 only) */
static void backup_h5(const char *h5name) {
    char tmp[300];
    char bak[300];
    snprintf(tmp, sizeof(tmp), "%s.bak.tmp", h5name);
    snprintf(bak, sizeof(bak), "%s.bak", h5name);
    copy_file(h5name, tmp);
    error(rename(tmp, bak) != 0, 1, "backup_h5", "rename failed");
}

/* ------------------------------------------------------------------ hdf5 (PID 0 only) */

static void h5_attr_int(hid_t fid, const char *name, int v) {
    hid_t sp = H5Screate(H5S_SCALAR);
    hid_t at = H5Acreate2(fid, name, H5T_NATIVE_INT, sp, H5P_DEFAULT, H5P_DEFAULT);
    H5Awrite(at, H5T_NATIVE_INT, &v);
    H5Aclose(at);
    H5Sclose(sp);
}

static void h5_attr_double(hid_t fid, const char *name, double v) {
    hid_t sp = H5Screate(H5S_SCALAR);
    hid_t at = H5Acreate2(fid, name, H5T_NATIVE_DOUBLE, sp, H5P_DEFAULT, H5P_DEFAULT);
    H5Awrite(at, H5T_NATIVE_DOUBLE, &v);
    H5Aclose(at);
    H5Sclose(sp);
}

/* empty extendable dataset: dims = (0, rest...), chunk = one row */
static void h5_create_dset(hid_t fid, const char *name, hid_t type, int rank, const hsize_t *rest) {
    hsize_t dims[6];
    hsize_t maxdims[6];
    hsize_t chunk[6];
    dims[0] = 0;
    maxdims[0] = H5S_UNLIMITED;
    chunk[0] = 1;
    for (int i = 1; i < rank; i++) {
        dims[i] = rest[i - 1];
        maxdims[i] = rest[i - 1];
        chunk[i] = rest[i - 1];
    }
    hid_t sp = H5Screate_simple(rank, dims, maxdims);
    hid_t pl = H5Pcreate(H5P_DATASET_CREATE);
    H5Pset_chunk(pl, rank, chunk);
    hid_t ds = H5Dcreate2(fid, name, type, sp, H5P_DEFAULT, pl, H5P_DEFAULT);
    error(ds < 0, 1, "h5_create_dset", "cannot create dataset");
    H5Dclose(ds);
    H5Pclose(pl);
    H5Sclose(sp);
}

/* append one row (rank-1 trailing dims taken from the dataset) */
static void h5_append_row(hid_t fid, const char *name, hid_t type, const void *row) {
    hid_t ds = H5Dopen2(fid, name, H5P_DEFAULT);
    error(ds < 0, 1, "h5_append_row", "cannot open dataset");
    hid_t sp = H5Dget_space(ds);
    int rank = H5Sget_simple_extent_ndims(sp);
    hsize_t dims[6];
    H5Sget_simple_extent_dims(sp, dims, NULL);
    H5Sclose(sp);
    hsize_t newdims[6];
    hsize_t start[6];
    hsize_t count[6];
    for (int i = 0; i < rank; i++) {
        newdims[i] = dims[i];
        start[i] = 0;
        count[i] = dims[i];
    }
    newdims[0] = dims[0] + 1;
    start[0] = dims[0];
    count[0] = 1;
    error(H5Dset_extent(ds, newdims) < 0, 1, "h5_append_row", "cannot extend dataset");
    hid_t fsp = H5Dget_space(ds);
    H5Sselect_hyperslab(fsp, H5S_SELECT_SET, start, NULL, count, NULL);
    hid_t msp = H5Screate_simple(rank, count, NULL);
    error(H5Dwrite(ds, type, msp, fsp, H5P_DEFAULT, row) < 0, 1, "h5_append_row", "write failed");
    H5Sclose(msp);
    H5Sclose(fsp);
    H5Dclose(ds);
}

static hsize_t h5_nrows(hid_t fid, const char *name) {
    hid_t ds = H5Dopen2(fid, name, H5P_DEFAULT);
    error(ds < 0, 1, "h5_nrows", "cannot open dataset");
    hid_t sp = H5Dget_space(ds);
    hsize_t dims[6];
    H5Sget_simple_extent_dims(sp, dims, NULL);
    H5Sclose(sp);
    H5Dclose(ds);
    return dims[0];
}

static void h5_set_nrows(hid_t fid, const char *name, hsize_t nrows) {
    hid_t ds = H5Dopen2(fid, name, H5P_DEFAULT);
    hid_t sp = H5Dget_space(ds);
    hsize_t dims[6];
    H5Sget_simple_extent_dims(sp, dims, NULL);
    H5Sclose(sp);
    dims[0] = nrows;
    error(H5Dset_extent(ds, dims) < 0, 1, "h5_set_nrows", "cannot shrink dataset");
    H5Dclose(ds);
}

static const char *h5_dsets[5] = { "/traj", "/plaq", "/glue", "/tor", "/topo" };

static void h5_create_file(const char *h5name, int nlev, int nflow) {
    hid_t fid = H5Fcreate(h5name, H5F_ACC_EXCL, H5P_DEFAULT, H5P_DEFAULT);
    error(fid < 0, 1, "h5_create_file", "cannot create h5 file");
    hsize_t rest_glue[4] = { (hsize_t)nlev, (hsize_t)total_n_glue_op, (hsize_t)GLB_T, 2 };
    hsize_t rest_tor[3] = { (hsize_t)total_n_tor_op, (hsize_t)GLB_T, 2 };
    hsize_t rest_topo[2] = { (hsize_t)nflow, 4 };
    h5_create_dset(fid, "/traj", H5T_NATIVE_INT, 1, NULL);
    h5_create_dset(fid, "/plaq", H5T_NATIVE_DOUBLE, 1, NULL);
    h5_create_dset(fid, "/glue", H5T_NATIVE_DOUBLE, 5, rest_glue);
    h5_create_dset(fid, "/tor", H5T_NATIVE_DOUBLE, 4, rest_tor);
    h5_create_dset(fid, "/topo", H5T_NATIVE_DOUBLE, 3, rest_topo);
    h5_attr_int(fid, "NG", NG);
    h5_attr_int(fid, "GLB_T", GLB_T);
    h5_attr_int(fid, "GLB_X", GLB_X);
    h5_attr_int(fid, "GLB_Y", GLB_Y);
    h5_attr_int(fid, "GLB_Z", GLB_Z);
    h5_attr_double(fid, "beta", pg_var.beta);
    h5_attr_int(fid, "nhb", pg_var.nhb);
    h5_attr_int(fid, "nor", pg_var.nor);
    h5_attr_int(fid, "ObsInterval", run_var.ObsInterval);
    h5_attr_int(fid, "therm", run_var.therm);
    h5_attr_int(fid, "nblkstart", gb_var.nblkstart);
    h5_attr_int(fid, "nblkend", gb_var.nblkend);
    h5_attr_double(fid, "APEsmear", gb_var.APEsmear);
    h5_attr_int(fid, "total_n_glue_op", total_n_glue_op);
    h5_attr_int(fid, "total_n_tor_op", total_n_tor_op);
    h5_attr_double(fid, "WF_tmax", WF_var.tmax);
    h5_attr_int(fid, "WF_nmeas", WF_var.nmeas);
    h5_attr_int(fid, "WF_integrator", (int)WF_var.ittype);
    h5_attr_double(fid, "WF_eps", WF_var.eps);
    h5_attr_double(fid, "WF_delta", WF_var.delta);
    H5Fclose(fid);
}

/* resume: open (restore from .bak if needed), keep only rows with traj <= ckpt */
static void h5_resume(const char *h5name, int ckpt) {
    char bak[300];
    snprintf(bak, sizeof(bak), "%s.bak", h5name);
    H5Eset_auto2(H5E_DEFAULT, NULL, NULL);
    hid_t fid = -1;
    if (file_exists(h5name)) { fid = H5Fopen(h5name, H5F_ACC_RDWR, H5P_DEFAULT); }
    if (fid < 0) {
        error(!file_exists(bak), 1, "h5_resume", "h5 file unreadable and no .bak");
        lprintf("H5", 0, "%s unreadable: restoring from %s\n", h5name, bak);
        copy_file(bak, h5name);
        fid = H5Fopen(h5name, H5F_ACC_RDWR, H5P_DEFAULT);
        error(fid < 0, 1, "h5_resume", "restored h5 file unreadable");
    }
    hsize_t ntraj = h5_nrows(fid, "/traj");
    int *traj = malloc(sizeof(int) * (ntraj + 1));
    if (ntraj > 0) {
        hid_t ds = H5Dopen2(fid, "/traj", H5P_DEFAULT);
        H5Dread(ds, H5T_NATIVE_INT, H5S_ALL, H5S_ALL, H5P_DEFAULT, traj);
        H5Dclose(ds);
    }
    hsize_t nkeep = 0;
    while (nkeep < ntraj && traj[nkeep] <= ckpt) {
        nkeep++;
    }
    free(traj);
    for (int i = 0; i < 5; i++) {
        hsize_t nr = h5_nrows(fid, h5_dsets[i]);
        error(nr < nkeep, 1, "h5_resume", "dataset shorter than /traj: inconsistent h5, use the .bak");
        if (nr != nkeep) {
            lprintf("H5", 0, "shrinking %s from %llu to %llu rows\n", h5_dsets[i], (unsigned long long)nr,
                    (unsigned long long)nkeep);
            h5_set_nrows(fid, h5_dsets[i], nkeep);
        }
    }
    lprintf("H5", 0, "resume: %s has %llu measurements with traj <= %d\n", h5name, (unsigned long long)nkeep, ckpt);
    H5Fclose(fid);
    H5Eset_auto2(H5E_DEFAULT, (H5E_auto2_t)H5Eprint2, stderr);
}

/* append one measurement; /traj is written LAST */
static void h5_append(const char *h5name, int traj, double plaq, const double *glue, const double *tor, const double *topo) {
    hid_t fid = H5Fopen(h5name, H5F_ACC_RDWR, H5P_DEFAULT);
    error(fid < 0, 1, "h5_append", "cannot open h5 file");
    h5_append_row(fid, "/plaq", H5T_NATIVE_DOUBLE, &plaq);
    h5_append_row(fid, "/glue", H5T_NATIVE_DOUBLE, glue);
    h5_append_row(fid, "/tor", H5T_NATIVE_DOUBLE, tor);
    h5_append_row(fid, "/topo", H5T_NATIVE_DOUBLE, topo);
    h5_append_row(fid, "/traj", H5T_NATIVE_INT, &traj);
    H5Fflush(fid, H5F_SCOPE_GLOBAL);
    H5Fclose(fid);
}

/* ------------------------------------------------------------------ MPI gather over T */

/* local[T][nper] (complex as 2 doubles) on every rank -> glb[GLB_T][nper] on PID 0.
 * Blocks are placed by each rank's zerocoord[0] (only NP_T > 1 is supported by the spatial
 * transformations, so a rank owns a contiguous block of T timeslices). */
static void gather_T(const hr_complex *local, int nper, hr_complex *glb) {
    int nloc = 2 * T * nper;
#ifdef WITH_MPI
    int nproc = NP_T * NP_X * NP_Y * NP_Z;
    static double *recv = NULL;
    static int recv_len = 0;
    static int *t0 = NULL;
    if (PID == 0 && recv_len < nloc * nproc) {
        free(recv);
        recv = malloc(sizeof(double) * nloc * nproc);
        recv_len = nloc * nproc;
    }
    if (PID == 0 && t0 == NULL) { t0 = malloc(sizeof(int) * nproc); }
    MPI_Gather((void *)local, nloc, MPI_DOUBLE, recv, nloc, MPI_DOUBLE, 0, GLB_COMM);
    MPI_Gather(&zerocoord[0], 1, MPI_INT, t0, 1, MPI_INT, 0, GLB_COMM);
    if (PID == 0) {
        for (int r = 0; r < nproc; r++) {
            memcpy((double *)glb + 2 * (size_t)t0[r] * nper, recv + (size_t)r * nloc, sizeof(double) * nloc);
        }
    }
#else
    memcpy(glb, local, sizeof(double) * nloc);
#endif
}

/* ------------------------------------------------------------------ checkpoints */

static void ckpt_names(int n, char *lat, char *rng) {
    sprintf(lat, "ckpoint_lat.%d", n);
    sprintf(rng, "ckpoint_rng.%d", n);
}

static void save_checkpoint(int n, int prev) {
    char lat[64];
    char rng[64];
    ckpt_names(n, lat, rng);
    write_gauge_field(lat);
    write_ranlxd_state(rng);
    lprintf("CKPT", 0, "saved %s %s\n", lat, rng);
    if (prev >= 0 && PID == 0) {
        char plat[64];
        char prng[64];
        ckpt_names(prev, plat, prng);
        remove(plat);
        remove(prng);
        lprintf("CKPT", 0, "removed %s %s\n", plat, prng);
    }
}

/* ------------------------------------------------------------------ main */

int main(int argc, char *argv[]) {
    struct timeval start;
    struct timeval end;
    struct timeval etime;

    setup_process(&argc, &argv);
    setup_gauge_fields();

    /* defaults, then input */
    run_var.n_update = 0;
    run_var.ObsInterval = 20;
    run_var.therm = 0;
    strcpy(run_var.h5name, "glue_claude.h5");
    read_input(run_var.read, get_input_filename());
    read_input(pg_var.read, get_input_filename());
    read_input(gb_var.read, get_input_filename());
    WF_var.anisotropy = 1.0;
    read_input(WF_var.read, get_input_filename());

    error(NP_X != 1 || NP_Y != 1 || NP_Z != 1, 1, "main", "only NP_T > 1 is supported");
    error(GLB_T % NP_T != 0, 1, "main", "GLB_T must be divisible by NP_T");
    error(run_var.ObsInterval < 1, 1, "main", "ObsInterval must be >= 1");

    lprintf("MAIN", 0, "beta=%lf nhb=%d nor=%d\n", pg_var.beta, pg_var.nhb, pg_var.nor);
    lprintf("MAIN", 0, "n_update=%d ObsInterval=%d therm=%d h5file=%s\n", run_var.n_update, run_var.ObsInterval,
            run_var.therm, run_var.h5name);
    lprintf("MAIN", 0, "glueballs: nblkstart=%d nblkend=%d APEsmear=%lf, total_n_glue_op=%d total_n_tor_op=%d\n",
            gb_var.nblkstart, gb_var.nblkend, gb_var.APEsmear, total_n_glue_op, total_n_tor_op);
    lprintf("MAIN", 0, "WF: integrator=%d tmax=%lf nmeas=%d eps=%lf delta=%lf\n", (int)WF_var.ittype, WF_var.tmax,
            WF_var.nmeas, WF_var.eps, WF_var.delta);

    BCs_pars_t BCs_pars = { .fermion_twisting_theta = { 0., 0., 0., 0. },
                            .gauge_boundary_improvement_cs = 1.,
                            .gauge_boundary_improvement_ct = 1.,
                            .chiSF_boundary_improvement_ds = 1.,
                            .SF_BCs = 0 };
    init_BCs(&BCs_pars);
    WF_initialize();
    initialize_spatial_active_slices(NULL);
    error(n_active_slices != T, 1, "main", "expected all local timeslices to be active");
    report_gb_group_setup();
    report_tor_group_setup();

    int nlev = gb_var.nblkend - gb_var.nblkstart + 1;
    int nflow = WF_var.nmeas + 1;
    int nper_glue = nlev * total_n_glue_op;

    /* start: fresh (hot) or from checkpoint */
    int start_n = 0;
    int prev_ckpt = -1;
    const char *cks = getenv("CheckpointStart");
    if (cks != NULL && cks[0] != '\0') {
        start_n = atoi(cks);
        char lat[64];
        char rng[64];
        ckpt_names(start_n, lat, rng);
        error(!file_exists(lat) || !file_exists(rng), 1, "main", "CheckpointStart: ckpoint_lat/rng.<n> not found");
        lprintf("MAIN", 0, "CheckpointStart: resuming from %d\n", start_n);
        read_gauge_field(lat);
        read_ranlxd_state(rng);
        prev_ckpt = start_n;
        if (PID == 0) { h5_resume(run_var.h5name, start_n); }
    } else {
        error(PID == 0 && file_exists(run_var.h5name), 1, "main", "h5 file exists: set CheckpointStart to resume");
        lprintf("MAIN", 0, "fresh start from a random (hot) configuration\n");
        random_u(u_gauge);
        if (PID == 0) { h5_create_file(run_var.h5name, nlev, nflow); }
    }
    apply_BCs_on_fundamental_gauge_field();
    represent_gauge_field();
    lprintf("MAIN", 0, "initial plaquette %1.16e\n", avr_plaquette());

    /* buffers */
    hr_complex *gb_loc = amalloc(sizeof(hr_complex) * nper_glue * T, ALIGN);
    hr_complex *tor_loc = amalloc(sizeof(hr_complex) * total_n_tor_op * T, ALIGN);
    hr_complex **polyf = amalloc(sizeof(hr_complex *) * 3, ALIGN);
    polyf[0] = amalloc(sizeof(hr_complex) * Y * Z * T, ALIGN);
    polyf[1] = amalloc(sizeof(hr_complex) * X * Z * T, ALIGN);
    polyf[2] = amalloc(sizeof(hr_complex) * X * Y * T, ALIGN);
    error(gb_loc == NULL || tor_loc == NULL || polyf[0] == NULL || polyf[1] == NULL || polyf[2] == NULL, 1, "main",
          "cannot allocate measurement buffers");
    hr_complex *gb_glb = NULL;
    hr_complex *tor_glb = NULL;
    double *glue_row = NULL;
    double *tor_row = NULL;
    double *topo_row = malloc(sizeof(double) * nflow * 4);
    if (PID == 0) {
        gb_glb = malloc(sizeof(hr_complex) * nper_glue * GLB_T);
        tor_glb = malloc(sizeof(hr_complex) * total_n_tor_op * GLB_T);
        glue_row = malloc(sizeof(double) * 2 * nper_glue * GLB_T);
        tor_row = malloc(sizeof(double) * 2 * total_n_tor_op * GLB_T);
        error(gb_glb == NULL || tor_glb == NULL || glue_row == NULL || tor_row == NULL, 1, "main",
              "cannot allocate gather buffers");
    }
    suNg_field *Vwf = alloc_suNg_field(&glattice);

    int end_n = start_n + run_var.n_update;
    for (int n = start_n + 1; n <= end_n; n++) {
        gettimeofday(&start, 0);
        update(&(pg_var.beta), pg_var.nhb, pg_var.nor);
        gettimeofday(&end, 0);
        timeval_subtract(&etime, &end, &start);
        lprintf("MAIN", 0, "update %d plaquette %1.16e [%ld sec %ld usec]\n", n, avr_plaquette(), etime.tv_sec,
                etime.tv_usec);

        if (n <= run_var.therm || n % run_var.ObsInterval != 0) { continue; }

        /* 1a. glueballs: layout [t][level][op] */
        gettimeofday(&start, 0);
        for (int i = 0; i < nper_glue * T; i++) {
            gb_loc[i] = 0.;
        }
        measure_1pt_glueballs(gb_var.nblkstart, gb_var.nblkend, &(gb_var.APEsmear), gb_loc);
        gettimeofday(&end, 0);
        timeval_subtract(&etime, &end, &start);
        lprintf("MAIN", 0, "update %d glueballs [%ld sec %ld usec]\n", n, etime.tv_sec, etime.tv_usec);

        /* 1b. torelons: layout [t][op] */
        gettimeofday(&start, 0);
        for (int i = 0; i < total_n_tor_op * T; i++) {
            tor_loc[i] = 0.;
        }
        for (int i = 0; i < Y * Z * T; i++) {
            polyf[0][i] = 0.;
        }
        for (int i = 0; i < X * Z * T; i++) {
            polyf[1][i] = 0.;
        }
        for (int i = 0; i < X * Y * T; i++) {
            polyf[2][i] = 0.;
        }
        measure_1pt_torellons(&(gb_var.APEsmear), tor_loc, polyf);
        gettimeofday(&end, 0);
        timeval_subtract(&etime, &end, &start);
        lprintf("MAIN", 0, "update %d torelons [%ld sec %ld usec]\n", n, etime.tv_sec, etime.tv_usec);

        /* 1c. Wilson flow on a copy: (t, E, Esym, Q) at nflow flow times */
        gettimeofday(&start, 0);
        copy_suNg_field(Vwf, u_gauge);
        data_storage_array *wf = WF_update_and_measure(WF_var.ittype, Vwf, &(WF_var.tmax), &(WF_var.eps),
                                                       &(WF_var.delta), WF_var.nmeas, STORE);
        for (int k = 0; k < nflow; k++) {
            for (int c = 0; c < 4; c++) {
                int idx[2] = { k, c };
                topo_row[4 * k + c] = *data_storage_element(wf, 0, idx);
            }
        }
        free_data_storage(wf);
        gettimeofday(&end, 0);
        timeval_subtract(&etime, &end, &start);
        lprintf("MAIN", 0, "update %d Wilson flow t=%lf Q=%1.10e [%ld sec %ld usec]\n", n, topo_row[4 * (nflow - 1)],
                topo_row[4 * (nflow - 1) + 3], etime.tv_sec, etime.tv_usec);

        double plaq = avr_plaquette();

        /* 1d. gather all timeslices on PID 0 */
        gather_T(gb_loc, nper_glue, gb_glb);
        gather_T(tor_loc, total_n_tor_op, tor_glb);

        /* 2. PID 0: reorder to the h5 layout, backup, append */
        if (PID == 0) {
            gettimeofday(&start, 0);
            for (int t = 0; t < GLB_T; t++) {
                for (int l = 0; l < nlev; l++) {
                    for (int op = 0; op < total_n_glue_op; op++) {
                        hr_complex v = gb_glb[((size_t)t * nlev + l) * total_n_glue_op + op];
                        size_t o = (((size_t)l * total_n_glue_op + op) * GLB_T + t) * 2;
                        glue_row[o] = creal(v);
                        glue_row[o + 1] = cimag(v);
                    }
                }
                for (int op = 0; op < total_n_tor_op; op++) {
                    hr_complex v = tor_glb[(size_t)t * total_n_tor_op + op];
                    size_t o = ((size_t)op * GLB_T + t) * 2;
                    tor_row[o] = creal(v);
                    tor_row[o + 1] = cimag(v);
                }
            }
            backup_h5(run_var.h5name);
            h5_append(run_var.h5name, n, plaq, glue_row, tor_row, topo_row);
            gettimeofday(&end, 0);
            timeval_subtract(&etime, &end, &start);
            lprintf("MAIN", 0, "update %d h5 backup + append [%ld sec %ld usec]\n", n, etime.tv_sec, etime.tv_usec);
        }

        /* 3.+4. checkpoint, then prune the previous one */
        save_checkpoint(n, prev_ckpt);
        prev_ckpt = n;
    }

    lprintf("MAIN", 0, "done: last update %d, last checkpoint %d\n", end_n, prev_ckpt);

    free_suNg_field(Vwf);
    afree(gb_loc);
    afree(tor_loc);
    afree(polyf[0]);
    afree(polyf[1]);
    afree(polyf[2]);
    afree(polyf);
    free(topo_row);
    if (PID == 0) {
        free(gb_glb);
        free(tor_glb);
        free(glue_row);
        free(tor_row);
    }
    finalize_process();
    return 0;
}
