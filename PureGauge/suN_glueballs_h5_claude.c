/***************************************************************************\
* Quenched SU(N) generation + in-process glueball / torelon / topology
* measurement, appended to ONE HDF5 file per stream.
* Plan: QuenchedSU4_claude/quenched_su4_glueball_impl_plan_claude.md (Chunk 2)
\***************************************************************************/

/*
 * Update: Wilson action, Cabibbo-Marinari SU(2)-subgroup heatbath (N. Cabibbo and E. Marinari,
 *   Phys. Lett. B119 (1982) 387) + overrelaxation (M. Creutz, Phys. Rev. D36 (1987) 515;
 *   F. R. Brown and T. J. Woch, Phys. Rev. Lett. 58 (1987) 2394): HiRep update(), nhb HB + nor OR
 *   sweeps per update.
 * Glueballs / torelons: Wilson loops projected onto O_h irreps and the little groups of moving
 *   frames (B. Berg and A. Billoire, Nucl. Phys. B221 (1983) 109; R. C. Johnson, Phys. Lett. B114
 *   (1982) 147), generated by A. Rago's OpProjection.m (patched copy, GridBridge_claude), measured
 *   on APE-smeared (M. Albanese et al., Phys. Lett. B192 (1987) 163) and spatially blocked
 *   (M. Teper, Phys. Lett. B183 (1987) 345) links: measure_1pt_glueballs / measure_1pt_torellons.
 * Topology: Wilson flow (M. Luscher, JHEP 1008 (2010) 071, arXiv:1006.4518), HiRep
 *   WF_update_and_measure, (t, E, Esym, Q) at WF:nmeas+1 flow times.
 *
 * Cycle at a measurement point n (n > therm and n % ObsInterval == 0):
 *   1. measure glueballs, torelons, flow (on a copy of the links); gather all timeslices on PID 0
 *   2. PID 0: copy <h5> -> <h5>.bak (via <h5>.bak.tmp + rename), then append one row
 *   3. write ckpoint_lat.<n> + ckpoint_rng.<n> (HiRep gauge format + ranlxd state)
 *   4. remove the previous checkpoint pair (only after 3 succeeded)
 * So the h5 never lags the newest checkpoint; at most it is one row ahead (crash between 2 and 3).
 *
 * Resume: environment CheckpointStart=<n> loads ckpoint_{lat,rng}.<n>. The h5 is opened (restored
 *   from <h5>.bak if it cannot be opened) and shrunk to the rows with traj <= n. The ranlxd state
 *   is per rank: resume with the same NP_T.
 * n_update is ADDITIVE: a run performs updates start+1 .. start+n_update.
 *
 * h5 layout (datasets extendable along axis 0, one row per measurement):
 *   /traj (N) int, /plaq (N) double,
 *   /glue (N, nlev, total_n_glue_op, GLB_T, 2), /tor (N, total_n_tor_op, GLB_T, 2) (re, im),
 *   /topo (N, WF:nmeas+1, 4) = (t, E, Esym, Q).
 *   The operator/channel table is the [INIT Measure ML] block of the run log (report_*_group_setup).
 */

